-- Each record represents a view of a shortened URL
--
-- Built for saving about 1M views per second:
-- - No foreign key to urls: for every view, PostgreSQL would lock the link's row in urls to check it,
--   which almost halved the rate (583,200 instead of 1,068,500 views/s). So the servers delete a
--   link's views themselves when they delete the link (what ON DELETE CASCADE did).
-- - No primary key: every insert would write the same last page of its index. Nothing looks a view
--   up by its id.
-- - id is a BIGINT: an INT runs out after 2.1 billion views.
-- - visitor_hash is the SHA-256 as 32 bytes, not 64 hex characters.
CREATE TABLE IF NOT EXISTS views (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  url_id INT NOT NULL,

  ip_address INET,
  user_agent TEXT,
  referrer TEXT,
  visitor_hash BYTEA,

  link_type link_type_enum, -- the type of the link when it was viewed
  via_qr BOOLEAN, -- if the link was accessed via QR code

  -- Optional, if we do IP geolocation:
  country VARCHAR(100),
  city VARCHAR(100),


  created_at TIMESTAMPTZ DEFAULT now(),

  -- Ensure that if via_qr is true, link_type is NULL, and if via_qr is false, link_type is NOT NULL
  CONSTRAINT check_link_source
    CHECK (
     (via_qr = TRUE AND link_type IS NULL)
    OR
     (via_qr = FALSE AND link_type IS NOT NULL)
    )
);

-- For the stats of a link (WHERE url_id = $1) and deleting its views. New views land all over it,
-- so it costs the inserts nothing measurable (757,600 views/s with it, 744,300 without).
CREATE INDEX IF NOT EXISTS views_url_id ON views (url_id);
